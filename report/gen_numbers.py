"""Generate report/numbers.tex (LaTeX \\newcommand macros) from reports/results.json.

Every figure quoted in the report is a macro defined here, so no number in the
PDF is hand-typed — they all trace to a real pipeline run. Re-run after the
pipeline to refresh the report's numbers:

    python -m qc_pipeline --mode mock
    python report/gen_numbers.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
RESULTS = REPO / "reports" / "results.json"
OUT = HERE / "numbers.tex"


def pct(x: float) -> str:
    """Format a 0-1 fraction as a LaTeX percent string (e.g. 0.875 -> '87.5\\%')."""
    v = round(x * 100, 1)
    s = f"{int(v)}" if v == int(v) else f"{v}"
    return s + r"\%"


def texesc(s) -> str:
    """Escape LaTeX specials in free-text values (e.g. the '$0' in the cost note)."""
    repl = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
            "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(repl.get(c, c) for c in str(s))


def count_tests() -> int:
    """Collected test count (parametrized cases expanded), to match 'N passed'."""
    import subprocess
    try:
        out = subprocess.run(
            ["python3", "-m", "pytest", "--collect-only", "-q"],
            cwd=REPO, capture_output=True, text=True, timeout=120,
        ).stdout
        if (m := re.search(r"(\d+)\s+tests?\s+collected", out)):
            return int(m.group(1))
    except Exception:
        pass
    # Fallback: count test functions (under-counts parametrized cases).
    return sum(len(re.findall(r"^\s*def test_", f.read_text(), flags=re.M))
               for f in (REPO / "tests").glob("test_*.py"))


def main() -> None:
    m = json.loads(RESULTS.read_text())
    eq, aq, cr = m["extraction_quality"], m["alert_quality"], m["confidence_and_review"]
    perf, cost, cov = m["performance"], m["cost"], m["coverage"]
    p, b = eq["primary"], eq["baseline"]

    macros = {
        "nReports": m["run"]["n_reports"],
        "nFiles": cov["files_seen"],
        "coverageRate": pct(cov["coverage_rate"]),
        # reading accuracy
        "primaryFieldAcc": pct(p["field_accuracy"]),
        "primaryFieldsCorrect": p["fields_correct"],
        "primaryFieldsTotal": p["fields_total"],
        "primaryReportAcc": pct(p["report_accuracy"]),
        "primaryMAE": p["mean_absolute_error"],
        "baselineFieldAcc": pct(b["field_accuracy"]),
        "fieldAccGain": pct(eq["llm_value"]["field_accuracy_gain"]),
        # alerts
        "alertTP": aq["primary"]["tp"],
        "alertFP": aq["primary"]["fp"],
        "alertFN": aq["primary"]["fn"],
        "alertPrecision": pct(aq["primary"]["precision"]),
        "alertRecall": pct(aq["primary"]["recall"]),
        "baselineRecall": pct(aq["baseline"]["recall"]),
        "expectedAlerts": ", ".join(aq["expected_alert_sites"]),
        "predictedAlerts": ", ".join(aq["predicted_alert_sites"]),
        "baselineMissed": ", ".join(eq["llm_value"]["baseline_missed_alert_sites"]),
        # confidence / review
        "meanConfidence": pct(cr["mean_confidence"]),
        "reviewRate": pct(cr["review_rate"]),
        "reportsFlagged": cr["reports_flagged_for_review"],
        "flaggedSites": ", ".join(cr["flagged_sites"]),
        "baselineAgreement": pct(cr["baseline_agreement_rate"]),
        # performance / cost
        "meanLatency": f"{perf['mean_latency_ms']:.2f}",
        "throughput": f"{perf['throughput_reports_per_s']:,.0f}",
        "costNote": cost["note"],
        # meta
        "nTests": count_tests(),
        "runMode": m["run"]["mode"],
    }

    # Free-text values may contain LaTeX specials (e.g. "$0"); escape them.
    # The pct()/integer values are already LaTeX-safe and must not be re-escaped.
    free_text = {"costNote", "expectedAlerts", "predictedAlerts", "baselineMissed",
                 "flaggedSites", "runMode"}
    for k in free_text:
        macros[k] = texesc(macros[k])

    lines = ["% AUTO-GENERATED by gen_numbers.py from reports/results.json — do not edit.\n"]
    for name, val in macros.items():
        lines.append(rf"\newcommand{{\{name}}}{{{val}}}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(macros)} macros)")


if __name__ == "__main__":
    main()
